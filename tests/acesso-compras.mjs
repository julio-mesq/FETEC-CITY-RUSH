import assert from 'node:assert/strict';
import fs from 'node:fs';
const phone=fs.readFileSync(new URL('../dist/src/phone.js',import.meta.url),'utf8');
const world=fs.readFileSync(new URL('../dist/src/world.js',import.meta.url),'utf8');
const compra=phone.match(/else if\(tipo==='arma'\)\{(.*?)\}\n/)[1];
const executar=new Function('v','ARMAS','PRECOS_ARMAS','est','cb','J',compra);
const ARMAS=Array.from({length:7},(_,i)=>({n:'Arma '+i})),precos=[0,4500,7500,9000,18000,25000,0];
const est={armas:[0,6]},jogador={dinheiro:30000};let equipada=-1,saves=0,aviso='';
const cb={nivel(){throw Error('Compra não deve consultar reputação');},arma:i=>equipada=i,salvar:()=>saves++,aviso:t=>aviso=t};
executar(5,ARMAS,precos,est,cb,jogador);
assert.equal(equipada,5);assert.equal(jogador.dinheiro,5000);assert.equal(saves,1);assert.ok(est.armas.includes(5));
executar(4,ARMAS,precos,est,cb,jogador);assert.equal(aviso,'Saldo insuficiente');assert.equal(jogador.dinheiro,5000);
assert.doesNotMatch(phone,/NIVEL_ARMAS|Requer reputação/);
const trecho=world.match(/if\(!casaPack\)arr\.push\(\{ x, z, w: w \/ 2, d: d \/ 2 \}\);/)[0];
const lote=new Function('casaPack','arr','x','z','w','d',trecho),arr=[];
lote(true,arr,100,100,36,36);assert.equal(arr.length,0,'jardim e fachada da casa não podem ter barreira invisível');
lote(false,arr,100,100,30,30);assert.equal(arr.length,1,'colisão dos outros prédios deve ser preservada');
assert.match(world,/INT\.colisores/,'as colisões internas continuam funcionando');
console.log('acesso-compras: compra sem nível, saldo validado e casas sem barreira externa OK');
